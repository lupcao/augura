// Builds ../verifier.js (the checked-in bundle the page loads) from src/core.js and the lockfile-pinned
// @noble packages, then records its SHA-256 in ../verifier.js.sha256.
//   cd site/verify/source && npm ci && npm run build && npm test
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = (name) => JSON.parse(readFileSync(join(here, "node_modules", name, "package.json"), "utf8")).version;
const out = join(here, "..", "verifier.js");

await build({
  absWorkingDir: here,
  entryPoints: ["src/core.js"],
  outfile: out,
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  charset: "utf8",
  legalComments: "inline",
  minify: false,
  banner: {
    js:
      `// Augura Fair Draw verifier bundle. Generated by site/verify/source/build.mjs: do not edit.\n` +
      `// @noble/curves ${pkg("@noble/curves")} and @noble/hashes ${pkg("@noble/hashes")} (MIT, (c) Paul Miller), ` +
      `esbuild ${pkg("esbuild")}.`,
  },
  logLevel: "warning",
});

const sha = createHash("sha256").update(readFileSync(out)).digest("hex");
writeFileSync(join(here, "..", "verifier.js.sha256"), `${sha}  verifier.js\n`);
console.log(`verifier.js sha256 ${sha}`);
